#!/usr/bin/env python3
"""
Generates js/data.js with 3,200 sample movie records.

The app ships with this sample so it works offline out of the box.
To use the REAL Kaggle IMDb/Netflix dataset, open the app and click
"Import CSV" (top right) - no code changes needed.

Run:  python3 tools/generate_data.py
"""
import json
import math
import os
import random

random.seed(2025)
N = 3200

GENRES = ["Action", "Adventure", "Animation", "Comedy", "Crime", "Documentary",
          "Drama", "Fantasy", "Horror", "Mystery", "Romance", "Sci-Fi",
          "Thriller", "Family"]
LANGS = ["English"] * 12 + ["Hindi"] * 3 + ["Korean"] * 2 + ["Spanish"] * 2 + \
        ["French", "Japanese", "German", "Italian", "Tamil"]
STREAMS = ["Netflix"] * 5 + ["Prime Video"] * 3 + ["Disney+", "Max", "Hulu", "Theatrical", "Theatrical"]

ADJ = ["Silent", "Last", "Crimson", "Hidden", "Broken", "Midnight", "Golden", "Lost", "Final",
       "Electric", "Frozen", "Burning", "Distant", "Hollow", "Savage", "Gentle", "Neon", "Wild",
       "Forgotten", "Eternal", "Rising", "Fallen", "Secret", "Iron", "Velvet", "Shattered",
       "Endless", "Phantom", "Radiant", "Bitter", "Quiet", "Restless", "Scarlet", "Lonely"]
NOUN = ["Horizon", "Empire", "Garden", "Signal", "Harbor", "Kingdom", "Echo", "Voyage", "Mirror",
        "Fortress", "Summer", "Protocol", "Dynasty", "Season", "Orchard", "Legacy", "Frontier",
        "Thunder", "Compass", "River", "Cipher", "Carnival", "Archive", "Lantern", "Paradox",
        "Highway", "Witness", "Harvest", "Tide", "Syndicate", "Odyssey", "Reckoning", "Blueprint",
        "Wanderer", "Asylum", "Gambit", "Monsoon", "Uprising", "Masquerade", "Meridian"]
PLACE = ["Tokyo", "Lisbon", "Mumbai", "Berlin", "Cairo", "Oslo", "Havana", "Seoul", "Nairobi",
         "Prague", "Lagos", "Kyoto", "Lima", "Dublin", "Jaipur", "Vienna", "Marrakesh", "Reykjavik"]
NAME = ["Ava", "Leo", "Maya", "Orion", "Zara", "Felix", "Nora", "Kai", "Iris", "Arjun", "Luna",
        "Ravi", "Elena", "Jonas", "Sana", "Milo", "Tara", "Victor", "Anika", "Rafael"]
WORD = ["Dreams", "Shadows", "Secrets", "Stars", "Whispers", "Storms", "Ashes", "Promises",
        "Memories", "Strangers", "Fireflies", "Thieves", "Letters", "Ghosts", "Hearts", "Rebels"]


def make_title():
    t = random.randint(0, 9)
    if t == 0:
        return f"The {random.choice(ADJ)} {random.choice(NOUN)}"
    if t == 1:
        return f"{random.choice(ADJ)} {random.choice(NOUN)}"
    if t == 2:
        return f"{random.choice(NOUN)} of {random.choice(WORD)}"
    if t == 3:
        return f"The {random.choice(NOUN)} of {random.choice(PLACE)}"
    if t == 4:
        return f"{random.choice(NAME)} and the {random.choice(ADJ)} {random.choice(NOUN)}"
    if t == 5:
        return f"A {random.choice(ADJ)} {random.choice(WORD)[:-1]}"
    if t == 6:
        return f"{random.choice(PLACE)} {random.choice(NOUN)}"
    if t == 7:
        return f"Beyond the {random.choice(NOUN)}"
    if t == 8:
        return f"{random.choice(WORD)} in {random.choice(PLACE)}"
    return f"{random.choice(NAME)}'s {random.choice(NOUN)}"


def pick_year():
    # Weighted toward recent decades
    while True:
        y = int(random.triangular(1950, 2025, 2015))
        if 1950 <= y <= 2025:
            return y


rows = []
seen = set()
while len(rows) < N:
    title = make_title()
    key = title.lower()
    if key in seen:
        continue
    seen.add(key)

    g_count = random.choices([1, 2, 3], weights=[3, 5, 2])[0]
    genres = random.sample(GENRES, g_count)
    year = pick_year()
    base = random.gauss(6.4, 1.15)
    if "Documentary" in genres:
        base += 0.5
    if "Horror" in genres:
        base -= 0.35
    rating = round(min(9.6, max(1.6, base)), 1)
    votes = int(math.exp(random.gauss(9.6, 1.6)))
    votes = max(120, min(votes, 2_400_000))
    runtime = int(min(195, max(72, random.gauss(108, 19))))
    if "Animation" in genres or "Family" in genres:
        runtime = int(min(125, max(72, runtime - 14)))
    rows.append([len(rows), title, year, "|".join(genres), rating, votes, runtime,
                 random.choice(LANGS), random.choice(STREAMS)])

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "data.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Sample dataset (generated by tools/generate_data.py).\n")
    f.write("   Row: [id, title, year, genres(|), rating, votes, runtime, language, platform]\n")
    f.write("   Use the in-app 'Import CSV' button to load the real Kaggle dataset. */\n")
    f.write("window.MOVIES_DATA = ")
    f.write(json.dumps(rows, ensure_ascii=False, separators=(",", ":")))
    f.write(";\n")
print(f"wrote {len(rows)} rows -> {os.path.normpath(out)}")
